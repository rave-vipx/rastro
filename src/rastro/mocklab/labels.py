"""The synthetic label every Mock Lab artifact carries (MOCK-004).

Mutations and failure scenarios reuse ``SyntheticLabel``; it is deliberately small,
versioned and stable. HTML artifacts embed it as a leading comment and JSON artifacts
under ``SYNTHETIC_KEY``, a key no source document is expected to use.
"""

from __future__ import annotations

import json
import re
from typing import Literal

from pydantic import Field, ValidationError

from rastro.domain.sources import Contract
from rastro.mocklab.errors import MockLabError

SYNTHETIC_KEY = "__rastro_synthetic__"
"""The JSON object key that holds the label in every generated JSON artifact."""

MAX_SEED = 2**63 - 1
_COMMENT = re.compile(r"\A<!-- rastro-synthetic (\{[^<>]*\}) -->\n")

type ArtifactKind = Literal["fixture", "mutation", "failure"]


class SyntheticLabel(Contract):
    """Marks an artifact as generated by Rastro, never as observed source data."""

    synthetic: Literal[True] = True
    generator: Literal["rastro.mocklab"] = "rastro.mocklab"
    label_version: Literal[1] = 1
    kind: ArtifactKind
    seed: int = Field(ge=0, le=MAX_SEED)

    def to_json(self) -> dict[str, object]:
        return self.model_dump(mode="json")

    def html_comment(self) -> str:
        """A leading HTML comment; parsers ignore it, readers cannot miss it."""
        payload = json.dumps(self.to_json(), sort_keys=True, separators=(",", ":"))
        return f"<!-- rastro-synthetic {payload} -->\n"


def label_html(body: str, label: SyntheticLabel) -> str:
    return label.html_comment() + body


def read_html_label(body: str) -> SyntheticLabel:
    """Return the label at the start of an HTML artifact or raise ``MockLabError``."""
    match = _COMMENT.match(body)
    if match is None:
        raise MockLabError("HTML artifact does not start with a synthetic label")
    try:
        return SyntheticLabel.model_validate_json(match.group(1))
    except ValidationError:
        raise MockLabError("HTML artifact carries an invalid synthetic label") from None


def label_json(payload: object, label: SyntheticLabel) -> dict[str, object]:
    """Put the label first in a JSON object; other roots cannot carry it and are refused."""
    if not isinstance(payload, dict):
        raise MockLabError("JSON artifacts require an object root to carry a synthetic label")
    if SYNTHETIC_KEY in payload:
        raise MockLabError("JSON input already uses the reserved synthetic label key")
    return {SYNTHETIC_KEY: label.to_json(), **payload}


def read_json_label(payload: object) -> SyntheticLabel:
    """Return the label of a decoded JSON artifact or raise ``MockLabError``."""
    if not isinstance(payload, dict) or SYNTHETIC_KEY not in payload:
        raise MockLabError("JSON artifact does not carry a synthetic label")
    try:
        return SyntheticLabel.model_validate(payload[SYNTHETIC_KEY])
    except ValidationError:
        raise MockLabError("JSON artifact carries an invalid synthetic label") from None
