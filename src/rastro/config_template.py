"""``rastro job template``: an annotated job file with every option commented (N18,
AGENT-001).

Uncommented lines form a minimal valid job (one URL source, one field, a CSS recipe);
every other key is a comment that shows its default (or a ``<type>`` placeholder), its
bounds and what it does. Without ``--all`` only the first variant of each recipe, field,
source, model and rule table is shown. Generated from the job models; never hand-edited.
"""

from __future__ import annotations

import json
from typing import Any

from rastro.config_reference import ConfigEntry, reference

# Values that make the uncommented lines a valid job; every path is in the first variant.
MINIMAL: dict[str, str] = {
    "format_version": "1",
    "sources[].url": '"https://example.com/events"',
    "fields[].name": '"title"',
    "fields[].type": '"string"',
    "acquisition.allowed_hosts": '["example.com"]',
    "recipe.strategy": '"css"',
    "recipe.fields": '{ title = "h2::text" }',
    "recipe.record_selector": '"article"',
}


def render_template(version: str, *, all_variants: bool = False) -> str:
    """The annotated TOML job; it validates as printed (``rastro job validate``)."""
    entries = [entry for entry in reference() if entry.kind == "job"]
    lines = [
        f"# Rastro job template (rastro {version}), generated by `rastro job template"
        f"{' --all' if all_variants else ''}`.",
        "# Uncommented lines are a minimal valid job: replace the example values. Uncomment",
        "# any other line to use it. Every key: `rastro config` or docs/configuration.md.",
        "# Unknown keys are rejected.",
    ]
    _Writer(entries, all_variants, lines).table("", None, commented=False)
    return "\n".join(lines) + "\n"


class _Writer:
    def __init__(self, entries: list[ConfigEntry], all_variants: bool, lines: list[str]):
        self.entries = entries
        self.all_variants = all_variants
        self.lines = lines
        self.paths = [entry.path for entry in entries]

    def table(self, prefix: str, variant: str | None, *, commented: bool) -> None:
        kids = [
            e
            for e in self.entries
            if e.path.startswith(prefix)
            and "." not in e.path[len(prefix) :]
            and (variant is None or e.variant == variant)
        ]
        for entry in [e for e in kids if not self._is_section(e)]:
            self._key(entry, commented=commented)
        for entry in [e for e in kids if self._is_section(e)]:
            self._section(entry, commented=commented)

    def _section(self, entry: ConfigEntry, *, commented: bool) -> None:
        header = _header(entry, self.paths)
        if entry.same_as:
            same = _toml_path(entry.same_as)
            where = "the first variant" if same == _toml_path(entry.path) else f"[{same}]"
            self.lines += ["", f"# {header}: same keys as {where}"]
            return
        prefix = next(
            candidate
            for candidate in (entry.path + "[].", entry.path + ".<name>.", entry.path + ".")
            if any(p.startswith(candidate) for p in self.paths)
        )
        variants = list(dict.fromkeys(e.variant for e in self.entries if _child_of(e, prefix)))
        shown = variants if self.all_variants or len(variants) < 2 else variants[:1]
        for index, variant in enumerate(shown):
            off = commented or index > 0 or not any(key.startswith(prefix) for key in MINIMAL)
            note = f"  # {variant}" if variant and len(variants) > 1 else ""
            self.lines += ["", f"# {entry.description}"] if index == 0 else [""]
            self.lines.append(("# " if off else "") + header + note)
            self.table(prefix, variant if len(variants) > 1 else None, commented=off)
        if len(shown) < len(variants):
            others = ", ".join(variants[1:])
            self.lines.append(f"# Other variants: {others} (rastro job template --all)")

    def _key(self, entry: ConfigEntry, *, commented: bool) -> None:
        name = entry.path.rsplit(".", 1)[-1]
        detail = "; ".join(item for item in (entry.type, entry.bounds) if item)
        self.lines.append(f"# {entry.description} ({detail})")
        if not commented and entry.path in MINIMAL:
            self.lines.append(f"{name} = {MINIMAL[entry.path]}")
        elif entry.default in (None, "null"):
            self.lines.append(f"# {name} = <{entry.type}>")
        else:
            self.lines.append(f"# {name} = {_toml(json.loads(entry.default or 'null'))}")

    def _is_section(self, entry: ConfigEntry) -> bool:
        if entry.path in MINIMAL:  # an inline value; nested member keys live in the reference
            return False
        return bool(entry.same_as) or any(
            p.startswith((entry.path + ".", entry.path + "[].")) for p in self.paths
        )


def _child_of(entry: ConfigEntry, prefix: str) -> bool:
    return entry.path.startswith(prefix) and "." not in entry.path[len(prefix) :]


def _header(entry: ConfigEntry, paths: list[str]) -> str:
    name = _toml_path(entry.path)
    if any(p.startswith(entry.path + ".<name>.") for p in paths):
        return f"[{name}.NAME]"
    return f"[[{name}]]" if entry.type.startswith("array") else f"[{name}]"


def _toml_path(path: str) -> str:
    return path.replace("[]", "").replace("<name>", "NAME")


def _toml(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return "[" + ", ".join(_toml(item) for item in value) + "]"
    if isinstance(value, dict):
        items = ", ".join(f"{json.dumps(key)} = {_toml(item)}" for key, item in value.items())
        return "{ " + items + " }" if items else "{}"
    return json.dumps(value)
